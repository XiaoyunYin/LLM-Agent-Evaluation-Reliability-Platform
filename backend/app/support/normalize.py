"""Deterministic state normalization, versioned.

A state diff is only meaningful if two runs that did the same thing produce the
same snapshot. Several things in a real database defeat that, and each needs a
stated rule rather than an ad-hoc fix at comparison time:

| Source of nondeterminism | Rule |
|---|---|
| Timestamps | Not stored. `created_seq` is a monotonic integer instead. |
| Autogenerated IDs | Agent-created rows get content-derived surrogate keys. |
| Row ordering | Rows sorted by primary key; SQLite order is never relied on. |
| Nullable fields | `NULL` normalizes to the sentinel `None`, never to `""` or `0`. |
| Generated metadata | Excluded by an explicit per-table field list. |

**Why comments need surrogate keys.** A comment's `comment_id` is chosen by the
agent's tool call, so two correct runs produce different IDs for the same logical
comment. Diffing on the raw ID would report every correct run as a mismatch. The
surrogate is derived from the fields that carry meaning — ticket, author, reason
code, normalized body — so two logically identical comments collide by
construction and two different ones do not.

Changing any rule here changes what "the same state" means, so the version is
recorded on every snapshot and every frozen task.
"""

from __future__ import annotations

import hashlib
import re
import sqlite3
from typing import Any

NORMALIZATION_VERSION = "support_normalize_v1"

# Tables compared by the verifier, with the fields that participate. Anything not
# listed is excluded by construction rather than by a filter someone might forget.
TRACKED_TABLES: dict[str, tuple[str, ...]] = {
    "tickets": (
        "ticket_id", "customer_id", "priority", "status",
        "team_id", "assignee_id", "escalated",
    ),
    "comments": ("ticket_id", "author", "reason_code", "body_normalized"),
    "customers": ("customer_id", "name", "tier", "region"),
    "agents": ("agent_id", "name", "team_id", "active"),
    "teams": ("team_id", "name", "queue"),
    "policies": ("policy_id", "title", "topic"),
}

# Fields excluded from comparison, recorded explicitly so the exclusion is a
# documented decision rather than an omission.
EXCLUDED_FIELDS: dict[str, tuple[str, ...]] = {
    "tickets": ("subject", "body", "created_seq"),
    "comments": ("comment_id", "created_seq", "body"),
    "policies": ("body",),
}

_WHITESPACE = re.compile(r"\s+")


def normalize_text(value: Any) -> str | None:
    """Collapse whitespace and case so prose differences do not read as state changes.

    Comment *bodies* are normalized but not compared field-by-field; the
    normalized form feeds the surrogate key so two comments with the same meaning
    and trivially different spacing are one comment.
    """
    if value is None:
        return None
    return _WHITESPACE.sub(" ", str(value)).strip().lower()


def _surrogate_comment_key(row: dict[str, Any]) -> str:
    """Content-derived identity for an agent-created comment.

    Built from ticket, author, reason code, and normalized body — the fields that
    determine whether two comments are the same comment. The agent-chosen
    `comment_id` is deliberately excluded.
    """
    payload = "|".join(
        [
            str(row.get("ticket_id")),
            str(row.get("author")),
            str(row.get("reason_code")),
            str(normalize_text(row.get("body"))),
        ]
    )
    return "CMT#" + hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def _row_key(table: str, row: dict[str, Any]) -> str:
    if table == "comments":
        return _surrogate_comment_key(row)
    primary = {
        "tickets": "ticket_id",
        "customers": "customer_id",
        "agents": "agent_id",
        "teams": "team_id",
        "policies": "policy_id",
    }[table]
    return str(row[primary])


def snapshot(connection: sqlite3.Connection) -> dict[str, dict[str, dict[str, Any]]]:
    """Capture the tracked state as `{table: {row_key: {field: value}}}`.

    Ordering is imposed by the mapping, not by SQLite, so a different query plan
    cannot change the result.
    """
    connection.row_factory = sqlite3.Row
    state: dict[str, dict[str, dict[str, Any]]] = {}

    for table, fields in TRACKED_TABLES.items():
        rows: dict[str, dict[str, Any]] = {}
        for raw in connection.execute(f"SELECT * FROM {table}"):
            row = dict(raw)
            if table == "comments":
                row["body_normalized"] = normalize_text(row.get("body"))
            key = _row_key(table, row)
            rows[key] = {
                field: (row.get(field) if row.get(field) is not None else None)
                for field in fields
            }
        state[table] = dict(sorted(rows.items()))

    return state


def diff(before: dict, after: dict) -> list[dict[str, Any]]:
    """Normalized state diff as a sorted list of atomic changes.

    Three change kinds, each atomic so a task can declare exactly one of them:

    - `row_added`    a row exists after and not before
    - `row_removed`  a row exists before and not after
    - `field_changed` one field of one row changed value

    A ticket whose priority and status both change produces **two** entries, so a
    task declaring only the priority change fails on the undeclared status change.
    That is the intended strictness.
    """
    changes: list[dict[str, Any]] = []

    for table in sorted(set(before) | set(after)):
        before_rows = before.get(table, {})
        after_rows = after.get(table, {})

        for key in sorted(set(after_rows) - set(before_rows)):
            changes.append(
                {"kind": "row_added", "table": table, "key": key,
                 "row": after_rows[key]}
            )
        for key in sorted(set(before_rows) - set(after_rows)):
            changes.append(
                {"kind": "row_removed", "table": table, "key": key,
                 "row": before_rows[key]}
            )
        for key in sorted(set(before_rows) & set(after_rows)):
            old, new = before_rows[key], after_rows[key]
            for field in sorted(set(old) | set(new)):
                if old.get(field) != new.get(field):
                    changes.append(
                        {
                            "kind": "field_changed",
                            "table": table,
                            "key": key,
                            "field": field,
                            "before": old.get(field),
                            "after": new.get(field),
                        }
                    )

    return changes


def change_signature(change: dict[str, Any]) -> str:
    """A stable string identifying one change, for set comparison.

    `row_added` deliberately signs only on table and key. The key is already
    content-derived for comments, so the row payload adds nothing, and including
    it would make a task declaration depend on field ordering.
    """
    if change["kind"] in {"row_added", "row_removed"}:
        return f"{change['kind']}:{change['table']}:{change['key']}"
    return (
        f"field_changed:{change['table']}:{change['key']}:"
        f"{change['field']}:{change['after']}"
    )
